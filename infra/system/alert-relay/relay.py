"""Alertmanager → Telegram relay.

Alertmanager calls POST /alert (its standard webhook) whenever a group of alerts
fires or resolves. This turns the payload into one short plain-language
message and sends it with a Telegram bot. Nothing here polls: no webhook call,
no message. (Alertmanager can talk to Telegram itself, but it would send raw
alert names; this keeps the same plain words as the Grafana dashboards.)

Configuration (all mounted files, re-read on every call so a changed secret
applies without a restart):
  /etc/telegram/bot_token, /etc/telegram/chat_id   from Secret Manager "shipzen-telegram"
  /etc/alert-text/alert-text.json             plain names, generated by observability/dashboards.py
If bot_token or chat_id is empty the relay accepts the webhook and logs that it
is not configured.

Standard library only, so it runs on a stock Python image.
"""
import json
import logging
import os
import urllib.error
import urllib.request
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

SECRET_DIR = os.getenv("SECRET_DIR", "/etc/telegram")
TEXT_FILE = os.getenv("TEXT_FILE", "/etc/alert-text/alert-text.json")
GRAFANA_URL = os.getenv("GRAFANA_URL", "https://grafana-shipzen.jeneeldumasia.codes")
API_URL = "https://api.telegram.org/bot{token}/sendMessage"
MAX_ALERTS = 6

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
log = logging.getLogger("alert-relay")


def _read(path: str) -> str:
    try:
        with open(path) as f:
            return f.read().strip()
    except OSError:
        return ""


def credentials():
    token, chat = _read(f"{SECRET_DIR}/bot_token"), _read(f"{SECRET_DIR}/chat_id")
    return (token, chat) if token and chat else None


def plain_text():
    try:
        return json.loads(_read(TEXT_FILE) or "{}")
    except ValueError:
        return {}


def format_message(payload: dict) -> str:
    words = plain_text()
    problems, severity = words.get("problems", {}), words.get("severity", {})
    alerts = payload.get("alerts", [])
    firing = [a for a in alerts if a.get("status") == "firing"]
    resolved = [a for a in alerts if a.get("status") == "resolved"]

    def line(a: dict, icon: str) -> str:
        labels, notes = a.get("labels", {}), a.get("annotations", {})
        name = labels.get("alertname", "Unknown problem")
        what = problems.get(name, name)
        where = labels.get("namespace") or labels.get("deployment") or ""
        sev = severity.get(labels.get("severity", ""), "")
        detail = notes.get("summary") or notes.get("description") or ""
        out = f"{icon} {what}"
        if where:
            out += f" ({where})"
        if sev and icon != "✅":
            out += f" [{sev}]"
        if detail:
            out += f"\n   {detail[:160]}"
        return out

    parts = []
    if firing:
        parts.append(f"ShipZen: {len(firing)} problem{'s' if len(firing) != 1 else ''}")
        parts += [line(a, "🔴") for a in firing[:MAX_ALERTS]]
    if resolved:
        parts.append("ShipZen: fixed")
        parts += [line(a, "✅") for a in resolved[:MAX_ALERTS]]
    hidden = max(0, len(firing) - MAX_ALERTS) + max(0, len(resolved) - MAX_ALERTS)
    if hidden:
        parts.append(f"…and {hidden} more")
    parts.append(GRAFANA_URL)
    return "\n".join(parts)[:1200]


def send(text: str) -> bool:
    creds = credentials()
    if not creds:
        log.warning("Telegram not configured (shipzen-telegram secret is empty); dropping message")
        return True  # nothing Alertmanager could fix by retrying
    token, chat = creds
    body = json.dumps({"chat_id": chat, "text": text, "disable_web_page_preview": True}).encode()
    req = urllib.request.Request(API_URL.format(token=token), data=body,
                                 headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=20) as resp:
            ok = 200 <= resp.status < 300
            log.info("Telegram answered %s", resp.status)
            return ok
    except urllib.error.HTTPError as e:  # never log the URL: it contains the bot token
        log.error("Telegram answered %s", e.code)
        # 4xx (bad token, unknown chat) won't fix itself; 429/5xx will
        return e.code < 500 and e.code != 429
    except Exception as e:
        log.error("Telegram request failed: %s", type(e).__name__)
        return False


class Handler(BaseHTTPRequestHandler):
    def _reply(self, code: int, body: str = "ok"):
        self.send_response(code)
        self.send_header("Content-Type", "text/plain")
        self.end_headers()
        self.wfile.write(body.encode())

    def do_GET(self):
        self._reply(200 if self.path == "/healthz" else 404)

    def do_POST(self):
        if self.path != "/alert":
            return self._reply(404, "not found")
        try:
            length = min(int(self.headers.get("Content-Length", 0)), 1_000_000)
            payload = json.loads(self.rfile.read(length) or b"{}")
        except ValueError:
            return self._reply(400, "bad json")
        # 5xx makes Alertmanager retry later; that is what we want if Telegram is down.
        self._reply(200 if send(format_message(payload)) else 502)

    def log_message(self, *args):  # keep request lines out of the log
        pass


if __name__ == "__main__":
    log.info("alert relay listening on :8080 (configured: %s)", bool(credentials()))
    ThreadingHTTPServer(("0.0.0.0", 8080), Handler).serve_forever()
